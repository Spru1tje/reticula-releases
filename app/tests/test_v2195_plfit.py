def _pv(x, c, w, e):
    return PR.pv_unit(x, c, w, e)


def _three_line_series(clamp=False, shift_grids=False, seed=3):
    """Two lines of the ratio and a third line; with clamp=True the third line is a small DIP in every other spectrum, so NNLS holds it at zero
    area there (the 'mixed' case: some spectra free, some with a line switched off)."""
    rng = np.random.default_rng(seed)
    out = []
    for i, t in enumerate(np.arange(293.0, 354.0, 10.0)):
        x = np.linspace(500, 580, 401) + (0.037 * i if shift_grids else 0.0)
        a3 = (-800.0 if i % 2 == 0 else 3e3) if clamp else 3e3
        y = 4e4 * _pv(x, 520, 3.8, 0.3) + 6e4 * _pv(x, 545, 3.8, 0.3) + a3 * _pv(x, 533, 3.5, 0.3)
        raw = rng.poisson(np.maximum(y + 300.0, 1.0)).astype(float)
        out.append({"T": float(t), "x": x, "y": raw - 300.0, "var": raw})
    return out


BANDS3 = [(520, 3.8), (545, 3.8), (533, 3.5)]


def _theta(m, seed=5):
    rng = np.random.default_rng(seed)
    return m.p0 + 1e-3 * rng.standard_normal(m.n_par) * np.maximum(1.0, np.abs(m.p0))


def _num_jac(m, th, h=1e-6):
    J = np.empty((len(m.residual(th)), m.n_par))
    for p in range(m.n_par):
        d = h * max(1.0, abs(th[p]))
        tp, tm = th.copy(), th.copy()
        tp[p] += d
        tm[p] -= d
        J[:, p] = (m.residual(tp) - m.residual(tm)) / (2 * d)
    return J


@pytest.mark.parametrize("drift", [False, True])
def test_exact_jacobian_equals_central_differences_on_a_common_grid(drift):
    m = PR._Model(_three_line_series(), BANDS3, (505, 565), 1, drift, drift, True)
    assert m.shared
    th = _theta(m)
    J, Jn = m.jacobian(th), _num_jac(m, th)
    assert np.abs(J - Jn).max() <= 1e-5 * np.abs(Jn).max()


@pytest.mark.parametrize("drift", [False, True])
def test_exact_jacobian_on_different_grids(drift):
    m = PR._Model(_three_line_series(shift_grids=True), BANDS3, (505, 565), 1, drift, drift, True)
    assert not m.shared                                                   # the per-spectrum path
    th = _theta(m)
    J, Jn = m.jacobian(th), _num_jac(m, th)
    assert np.abs(J - Jn).max() <= 1e-5 * np.abs(Jn).max()


@pytest.mark.parametrize("drift", [False, True])
def test_jacobian_when_nnls_holds_a_line_at_zero_in_some_spectra(drift):
    m = PR._Model(_three_line_series(clamp=True), BANDS3, (505, 565), 1, drift, drift, True)
    th = _theta(m)
    ev, batch = m._eval(th, with_batch=True)
    assert batch is not None and batch["good"].any() and not batch["good"].all()   # mixed: batched and NNLS spectra
    assert sorted({len(e[5]) for e in ev}) == [2, 3]
    J = m.jacobian(th)
    off = np.isin(m._pband, [2])
    Jn = _num_jac(m, th)
    # every parameter of the lines that are on: the exact derivative
    assert np.abs(J[:, ~off] - Jn[:, ~off]).max() <= 1e-5 * np.abs(Jn[:, ~off]).max()
    # the parameters of the line that is off somewhere: the forward difference of the pre-2.19.5 code (same step and bound rule)
    r0 = m.residual(th)
    for p in np.flatnonzero(off):
        h = 1e-4 * (1.0 if th[p] >= 0 else -1.0) * max(1.0, abs(th[p]))
        if th[p] + h > m.ub[p] or th[p] + h < m.lb[p]:
            h = -h
        tp = th.copy()
        tp[p] += h
        assert np.allclose(J[:, p], (m.residual(tp) - r0) / h, rtol=1e-10, atol=1e-10)


@pytest.mark.parametrize("clamp", [False, True])
def test_ratio_gradients_equal_differences_of_the_ratio(clamp):
    m = PR._Model(_three_line_series(clamp=clamp), BANDS3, (505, 565), 1, True, True, True)
    th = _theta(m)
    G = m.ratio_grads(th, [0], [1])
    off = np.isin(m._pband, [2]) if clamp else np.zeros(m.n_par, bool)
    for ti in range(len(m.data)):
        for p in np.flatnonzero(~off):
            h = 1e-6 * max(1.0, abs(th[p]))
            tp, tm = th.copy(), th.copy()
            tp[p] += h
            tm[p] -= h
            ap, am = m.solve(tp, ti)[0], m.solve(tm, ti)[0]
            num = (ap[0] / ap[1] - am[0] / am[1]) / (2 * h)
            assert abs(G[ti, p] - num) <= 1e-5 * max(1e-3, np.abs(G[ti]).max())
    # the batched version gives the per-spectrum one
    for ti in range(len(m.data)):
        g1 = m.ratio_grad(th, ti, [0], [1])
        assert np.allclose(G[ti, ~off], g1[~off], rtol=1e-9, atol=1e-12)


def test_noiseless_series_is_recovered_exactly():
    """Data made by the model itself (drifting pseudo-Voigt lines, linear background): the fit must return the true parameters and ratios."""
    x = np.linspace(500, 580, 801)
    T = np.linspace(293.0, 353.0, 7)
    truth = []
    sp = []
    for t in T:
        u = (t - T.mean()) / (T.max() - T.min()) * 2.0
        a1, a2 = 3e4 * math.exp(-700 / CM / (KB * t)) * 8, 5e4
        y = (a1 * _pv(x, 521.0 + 0.4 * u, 3.0 + 0.3 * u, 0.4) + a2 * _pv(x, 546.0 + 0.4 * u, 3.4 + 0.3 * u, 0.4)
             + 50.0 + 0.5 * (x - 540.0))
        sp.append({"T": float(t), "x": x, "y": y})
        truth.append(a1 / a2)
    f = PR.fit_global(sp, [(520.0, 3.5), (547.0, 3.5)], (505, 565), 1, "drift", False, 200)
    D = np.array([r["ratio"] for r in f["rows"]])
    assert np.allclose(D, truth, rtol=1e-6)
    assert f["rss"] < 1e-6 * sum(float(np.sum(s["y"] ** 2)) for s in sp)


