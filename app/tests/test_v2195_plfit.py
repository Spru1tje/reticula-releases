def test_old_relative_difference_step_failed_for_parameters_at_zero():
    """scipy's diff_step is RELATIVE: for a parameter at 5e-17 (eta of a Gaussian line on its bound) the old step was ~5e-21 and the column was
    rounding noise or exactly zero (here up to ~1e7, or 0, instead of ~10). The exact column equals a central difference with an absolute step."""
    from scipy.optimize._numdiff import approx_derivative
    sp = _series(lines=True)
    lines = PR.auto_lines(sp[0]["x"], np.mean([s["y"] for s in sp], 0), 505, 570)
    fa = PR.fit_global(sp, lines, (505, 570), 1, "none", True, 80, ([0, 1, 2], [3, 4, 5]))
    m = PR._Model(sp, lines, (505, 570), 1, False, False, True)
    th = np.array([fa["params"][n] for n in m.names])
    at0 = [i for i, n in enumerate(m.names) if n.startswith("e") and abs(th[i]) < 1e-12]
    assert at0                                                           # Gaussian lines: eta held at 0
    J = m.jacobian(th)
    Jn = _num_jac(m, th)
    Jold = approx_derivative(m.residual, th, method="2-point", rel_step=1e-4, bounds=(m.lb, m.ub))
    for i in at0:
        assert np.allclose(J[:, i], Jn[:, i], rtol=1e-5, atol=1e-6 * np.abs(Jn[:, i]).max())
        if th[i] != 0.0:                                                 # exactly 0 -> scipy falls back to an absolute step
            # rounding noise or nothing at all (the tiny step does not change the residual): off by at least half the column
            assert np.abs(Jold[:, i] - J[:, i]).max() >= 0.5 * np.abs(J[:, i]).max()


def test_ratio_errors_match_the_monte_carlo_scatter():
    """Known answer: the spread of the ratio over 60 noisy copies of the series. Parameters held on a bound are left out of the shape
    covariance (with them the errors were 1.3-1.4 x too large)."""
    sp0 = _series(lines=True)
    lines = PR.auto_lines(sp0[0]["x"], np.mean([s["y"] for s in sp0], 0), 505, 570)
    R, E = [], []
    for k in range(60):
        f = PR.fit_global(_series(seed=100 + k, lines=True), lines, (505, 570), 1, "none", True, 80, ([0, 1, 2], [3, 4, 5]))
        R.append([r["ratio"] for r in f["rows"]])
        E.append([r["ratio_err"] for r in f["rows"]])
    q = float(np.mean(np.mean(E, 0)) / np.mean(np.std(R, 0, ddof=1)))
    assert 0.85 < q < 1.2, q


