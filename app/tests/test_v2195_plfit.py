def test_a_warm_start_that_does_not_converge_is_redone_cold(monkeypatch):
    sp = _series(lines=True)
    b = PR.auto_lines(sp[0]["x"], np.mean([s["y"] for s in sp], 0), 505, 570)
    real = PR._fit_fixed
    seen = []

    def fake(*a):
        r = real(*a)
        seen.append(bool(a[8]))
        if a[8]:                                                         # pretend the warm start ran out of evaluations at a worse point
            r = dict(r, status=0, cost=r["cost"] + 1.0, rss=r["rss"] + 2.0)
        return r
    monkeypatch.setattr(PR, "_fit_fixed", fake)
    st = {"c0": 520.0}
    r = PR.fit_global(sp, b, (505, 570), 1, "none", True, 80, ([0, 1, 2], [3, 4, 5]), start=st)
    assert seen == [True, False] and r["warm_retry"] and r["status"] > 0
    monkeypatch.setattr(PR, "_fit_fixed", real)
    assert abs(r["rss"] / PR.fit_global(sp, b, (505, 570), 1, "none", True, 80, ([0, 1, 2], [3, 4, 5]))["rss"] - 1) < 1e-9


