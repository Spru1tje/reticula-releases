"""v2.24.2 (S-Structuur-1, S-Structuur-2): positive controls of the pattern route (indexing + Le Bail cell fit).
  S-1: hexagonal reference (corundum cell, repo reference). The pattern is generated by the app's Le Bail forward model
       from the cell-only phase (synthetic, the same kind of check as v2241). The route must find the hexagonal system and the cell.
  S-2: cubic reference CeO2 (repo CIF). The pattern is simulated by pymatgen's XRDCalculator from the CIF (an independent
       model, not the app's); the route must find a = 5.4113 Å within 0.02 Å.
Limits: synthetic (S-1) and simulated (S-2) patterns, no measured data. pymatgen and gemmi are required (no importorskip)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import numpy as np
import pytest
from mfs import vegard as VG
from mfs import rietveld as RV

APP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CEO2 = os.path.join(APP, "references", "library", "CeO2.cif")
CORUNDUM = (4.7606, 4.7606, 12.994, 90.0, 90.0, 120.0)


@pytest.mark.xfail(strict=True, reason="finding: indexing returns the sqrt(3)-supercell (a = 8.2456 = sqrt(3)*4.7606) of the "
                                       "hexagonal lattice instead of the primitive cell; the route does not reduce the cell")
def test_s1_hexagonal_pattern_route_recovers_the_hexagonal_cell():
    x = np.arange(10.0, 90.0, 0.02)
    ph = RV.Phase.from_cell(CORUNDUM, "corundum (synthetic)")
    R = RV.Refinement(x, np.ones_like(x) * 1000.0, [ph], "Cu Kα1", 6, "lebail", counts=True)
    D = R._design(R._values())
    y = D @ np.ones(D.shape[1])
    y = y / y.max() * 20000 + 300
    y = np.random.default_rng(7).poisson(y).astype(float)
    r = VG.cell_from_pattern(x, y, 10.0, 90.0)
    assert r["status"] == "ok", r
    assert r["system"] == "hexagonal"
    assert r["cell"][0] == pytest.approx(CORUNDUM[0], abs=0.02)
    assert r["cell"][2] == pytest.approx(CORUNDUM[2], abs=0.03)
    assert r["cell"][5] == pytest.approx(120.0, abs=1e-9)


def test_s2_cubic_ceo2_simulated_from_its_cif_gives_the_cell():
    from pymatgen.core import Structure
    from pymatgen.analysis.diffraction.xrd import XRDCalculator
    s = Structure.from_file(CEO2)
    pat = XRDCalculator(wavelength="CuKa").get_pattern(s, scaled=True, two_theta_range=(10, 90))
    x = np.arange(10.0, 90.0, 0.02)
    y = np.full_like(x, 50.0)
    for t, i in zip(pat.x, pat.y):
        y += 2000.0 * i / 100.0 * np.exp(-((x - t) / 0.08) ** 2)
    y = np.random.default_rng(3).poisson(y).astype(float)
    r = VG.cell_from_pattern(x, y, 10.0, 90.0)
    assert r["status"] == "ok", r
    assert r["system"] == "cubic"
    assert r["cell"][0] == pytest.approx(5.4113, abs=0.02)
