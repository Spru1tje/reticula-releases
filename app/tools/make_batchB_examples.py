"""EXAMPLE (synthetic) data for v2.5: TGA–MS ion currents, DSC Cp (blank / sapphire / sample), XPS S 2p, O 1s, C 1s."""
import os, sys, numpy as np, pandas as pd
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); EX = os.path.join(ROOT, "example_data")
sys.path.insert(0, ROOT)
rng = np.random.default_rng(7)
HDR = "# EXAMPLE DATA - synthetic, generated by Reticula for testing; not a measurement\n"
# --- TGA-MS (MOF801_Netzsch TGA, 10 K/min): H2O 83 + 294 °C, CO2 504 °C (+ small 294), CO 504 °C
T = np.arange(30, 800.1, 1.0)
g = lambda c, w, a: a * np.exp(-0.5 * ((T - c) / w) ** 2)
ms = pd.DataFrame({"Temperature (°C)": T,
                   "m/z 18 (A)": 2e-11 + g(83, 22, 6e-10) + g(294, 30, 2.5e-10) + g(504, 25, 1.5e-10),
                   "m/z 44 (A)": 1e-11 + g(294, 25, 3e-11) + g(504, 22, 9e-10),
                   "m/z 28 (A)": 5e-10 + g(504, 22, 1.2e-10)})
for c in ms.columns[1:]:
    ms[c] = ms[c] * (1 + rng.normal(0, 0.02, len(T)))
with open(os.path.join(EX, "TGA", "MOF801_QMS_ion_currents_EXAMPLE.csv"), "w") as fh:
    fh.write(HDR + "# QMS coupled to the TGA, ion currents vs sample temperature\n"); ms.to_csv(fh, index=False, float_format="%.4g")
# --- DSC Cp: 10 K/min, 20 -> 300 °C, 1 °C steps; blank curvature + small offset
os.makedirs(os.path.join(EX, "DSC", "Cp_sapphire"), exist_ok=True)
beta = 10.0; TT = np.arange(20, 300.01, 0.5); t = (TT - 20) / beta
base = -0.15 - 4e-4 * (TT - 20) + 2e-6 * (TT - 150) ** 2
sys.path.insert(0, ROOT); from mfs.dsc import cp_sapphire
def write(name, q, mass, extra=""):
    with open(os.path.join(EX, "DSC", "Cp_sapphire", name), "w") as fh:
        fh.write(HDR + f"# Sample mass: {mass} mg\n# 10 K/min, N2 50 mL/min, Al 40 uL pan{extra}\n")
        pd.DataFrame({"Time (min)": t, "Temperature (°C)": TT, "Heat Flow (mW)": q + rng.normal(0, 0.004, len(TT))}).to_csv(fh, index=False, float_format="%.5g")
endo = lambda m_mg, cp: -(m_mg * 1e-3) * cp * (beta / 60) * 1e3       # mW, exo-up
write("Cp_blank_EXAMPLE.csv", base, "0.00", " - empty pans")
write("Cp_sapphire_EXAMPLE.csv", base + endo(25.30, cp_sapphire(TT)), "25.30", " - sapphire disc")
cp_true = 0.62 + 1.6e-3 * (TT - 25)
write("Cp_sample_MOF-801_EXAMPLE.csv", base + endo(9.80, cp_true), "9.80", " - truth cp = 0.62 + 0.0016 (T - 25) J/g/K")
# --- XPS ZrO2@Sulfo-MOF801: S 2p (sulfonate 168.6 eV), O 1s (530.2 ZrO2 lattice + 531.8 carboxylate/OH), C 1s
sys.path.insert(0, ROOT); from mfs.xps import gl, DOUBLETS, shirley
def xps(name, x, comps, bg0, step_frac, noise=0.02):
    y = np.zeros_like(x)
    for reg, c, fw, ar in comps:
        y += gl(x, c, fw, 0.3, ar)
        d = DOUBLETS.get(reg)
        if d:
            y += gl(x, c + d["split"], fw, 0.3, ar * d["ratio"])
    cum = np.cumsum(y[::-1])[::-1]; cum = cum[0] - cum          # step rises to higher BE
    bg = bg0 + step_frac * cum / (cum.max() or 1) * y.max()
    yy = y + bg; yy = yy + rng.normal(0, noise * np.sqrt(yy.max() * yy / yy.max()), len(x))
    with open(os.path.join(EX, "XPS", name), "w") as fh:
        fh.write(HDR); pd.DataFrame({"Binding Energy (eV)": x[::-1], "Counts / s": np.round(yy[::-1], 1)}).to_csv(fh, index=False)
xps("ZrO2@Sulfo-MOF801_S2p_CasaXPS.csv", np.arange(160, 174.01, 0.05), [("S 2p", 168.6, 1.4, 1500.0)], 900, 0.08)
xps("ZrO2@Sulfo-MOF801_O1s_CasaXPS.csv", np.arange(526, 538.01, 0.05), [(None, 530.2, 1.3, 30000.0), (None, 531.8, 1.6, 26000.0)], 6000, 0.12)
xps("ZrO2@Sulfo-MOF801_C1s_CasaXPS.csv", np.arange(280, 294.01, 0.05), [(None, 284.8, 1.2, 6000.0), (None, 288.6, 1.3, 4500.0)], 1500, 0.05)
print("written")

# --- DSC heat–cool–heat (generic CSV): REAL heating 1 + SIMULATED cooling + SIMULATED heating 2 (peak −0.8 K, ΔH × 0.93)
from mfs import dsc as _dsc
FC = os.path.join(EX, "DSC", "full_cycle")
h = _dsc.read_dsc(os.path.join(FC, "SG_DSC_heating_Mettler_REAL.txt"))["curves"][0]
cfile = _dsc.read_dsc(os.path.join(FC, "SG_DSC_cooling_Mettler_EXAMPLE.txt"))
c = max(cfile["curves"], key=lambda c_: len(c_["T"]) if (_dsc.heating_rate(c_) or 0) < -0.05 else 0)
Th, qh, th = np.asarray(h["T"]), np.asarray(h["q"]), np.asarray(h["t"]) - h["t"][0]
Tc, qc, tc = np.asarray(c["T"]), np.asarray(c["q"]), np.asarray(c["t"]) - c["t"][0]
mb = (Th < 44) | (Th > 53)
bl = np.poly1d(np.polyfit(Th[mb], qh[mb], 1))
# shift in TIME (0.8 min at 1 K/min): the sample temperature lags during melting, so a shift on the T axis would distort the area
q2 = bl(Th) + 0.93 * (np.interp(th + 0.8, th, qh) - bl(np.interp(th + 0.8, th, Th)))
t1 = th; t2 = t1[-1] + 1 + tc; t3 = t2[-1] + 1 + th
df = pd.DataFrame({"Time (min)": np.concatenate([t1, t2, t3]), "Temperature (°C)": np.concatenate([Th, Tc, Th]),
                   f"Heat Flow ({h.get('unit')})": np.concatenate([qh, qc, q2 + rng.normal(0, 2e-4, len(q2))])})
with open(os.path.join(FC, "SG_DSC_heat-cool-heat_EXAMPLE.csv"), "w") as fh:
    fh.write(HDR + "# Heating 1 = REAL SG_DSC_1.1 data; cooling and heating 2 SIMULATED (heating 2: peak -0.8 K, dH x 0.93)\n"
             f"# Sample mass: {_dsc.read_dsc(os.path.join(FC, 'SG_DSC_heating_Mettler_REAL.txt'))['meta'].get('mass_mg')} mg\n")
    df.to_csv(fh, index=False, float_format="%.6g")
print("heat-cool-heat written", len(df))
