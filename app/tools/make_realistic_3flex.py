"""Write a MicroActive/3Flex-style *full report* Excel export (.xls) - EXAMPLE DATA, synthetic.

Real MicroActive "Export to Excel" files stack several reports on one sheet (header block, Summary, Isotherm
Tabular, BET, Langmuir, t-Plot, Isotherm Linear/Log Plot overlay columns, DFT). Every one of those tables has a
'Relative Pressure (P/Po)' and/or 'Quantity Adsorbed (cm3/g STP)' column - a reader that takes every such table
merges them into one zig-zagging series (the v1 bug). This file reproduces that structure for the tests."""
import os, sys
import numpy as np
import xlwt

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BANNER = "EXAMPLE DATA - synthetic, generated by MOF Figure Studio for testing; not a measurement"


def isotherm(p):
    # Sample A-like Type I: two micropore sites + small external surface + interparticle condensation
    return 62 * 9000 * p / (1 + 9000 * p) + 30 * 300 * p / (1 + 300 * p) + 6 * p + 25 * np.exp((p - 1) / 0.03)


def make(path, sample="Sample A batch 3", mass=0.0473, sheets="one"):
    rng = np.random.default_rng(7)
    pa = np.r_[np.logspace(-6, -2, 22), np.array([0.02, 0.03, 0.05, 0.07, 0.1, 0.13, 0.16, 0.2, 0.25, 0.3, 0.35,
                                                    0.4, 0.5, 0.6, 0.7, 0.8, 0.85, 0.9, 0.95, 0.99])]
    pd_ = np.array([0.95, 0.9, 0.85, 0.8, 0.7, 0.6, 0.5, 0.4, 0.3, 0.2, 0.15, 0.1])
    qa = isotherm(pa) * (1 + rng.normal(0, 0.002, pa.size))
    qd = isotherm(pd_) * 1.004 + 0.4
    p0 = 760.2
    wb = xlwt.Workbook()
    sh = wb.add_sheet("Report")
    r = [0]

    def w(*cells, sheet=None):
        s = sheet or sh
        for i, c in enumerate(cells):
            if c is not None:
                s.write(r[0], i, c)
        r[0] += 1

    w(BANNER)
    w("3Flex Version 6.02", None, None, "Serial # 1043", "Unit 1", "Port 2")
    w("Sample: " + sample)
    w("Operator: EXAMPLE", None, None, "Submitter: ")
    w("File: C:\\3Flex\\data\\SampleA_b3.SMP")
    w("Started: 11/3/2026 9:12:44 AM", None, None, "Analysis adsorptive: N2")
    w("Completed: 11/4/2026 2:01:10 AM", None, None, "Analysis bath temp.: 77.350 K")
    w(f"Sample mass: {mass:.4f} g", None, None, "Cold free space: 41.2241 cm³")
    w("Equilibration interval: 10 s", None, None, "Low pressure dose: 3.000 cm³/g STP")
    w()
    w("Summary Report")
    w("Surface Area")
    w("Single point surface area at P/Po = 0.200000000: 318.4021 m²/g")
    w("BET Surface Area: 335.0800 m²/g")
    w("Langmuir Surface Area: 431.8817 m²/g")
    w("t-Plot External Surface Area: 21.5531 m²/g")
    w("Pore Volume")
    w("Single point adsorption total pore volume of pores less than 41.4 nm diameter at P/Po = 0.950000000: 0.1537 cm³/g")
    w("t-Plot micropore volume: 0.1342 cm³/g")
    w()
    s2 = sh
    if sheets == "many":
        s2 = wb.add_sheet("Isotherm Tabular"); r[0] = 0
    w("Isotherm Tabular Report", sheet=s2)
    w("Relative Pressure (P/Po)", "Absolute Pressure (mmHg)", "Quantity Adsorbed (cm³/g STP)", "Elapsed Time (h:min)",
      "Saturation Pressure (mmHg)", sheet=s2)
    t = 0
    for p, q in zip(pa, qa):
        t += 17; w(float(p), float(p * p0), float(q), f"{t // 60:02d}:{t % 60:02d}", p0, sheet=s2)
    for p, q in zip(pd_, qd):
        t += 9; w(float(p), float(p * p0), float(q), f"{t // 60:02d}:{t % 60:02d}", p0, sheet=s2)
    w(sheet=s2)
    w("BET Surface Area Report", sheet=s2)
    w("BET Surface Area: 335.0800 ± 0.9124 m²/g", sheet=s2)
    w("Slope: 0.012967 g/cm³ STP", sheet=s2)
    w("Y-Intercept: 0.000012 g/cm³ STP", sheet=s2)
    w("C: 1081.4", sheet=s2)
    w("Qm: 76.9773 cm³/g STP", sheet=s2)
    w("Correlation Coefficient: 0.99981", sheet=s2)
    w("Molecular Cross-Sectional Area: 0.1620 nm²", sheet=s2)
    w("Relative Pressure (P/Po)", "Quantity Adsorbed (cm³/g STP)", "1/[Q(Po/P - 1)]", sheet=s2)
    m = (pa >= 0.05) & (pa <= 0.30)
    for p, q in zip(pa[m], qa[m]):
        w(float(p), float(q), float(1 / (q * (1 / p - 1))), sheet=s2)
    w(sheet=s2)
    w("Langmuir Surface Area Report", sheet=s2)
    w("Pressure (mmHg)", "Quantity Adsorbed (cm³/g STP)", "P/Q (mmHg·g/cm³ STP)", sheet=s2)
    for p, q in zip(pa[m], qa[m]):
        w(float(p * p0), float(q), float(p * p0 / q), sheet=s2)
    w(sheet=s2)
    w("t-Plot Report", sheet=s2)
    w("Thickness (nm)", "Quantity Adsorbed (cm³/g STP)", sheet=s2)
    m2 = (pa > 0.1) & (pa < 0.6)
    for p, q in zip(pa[m2], qa[m2]):
        w(float(0.1 * np.sqrt(13.99 / (0.034 - np.log10(p)))), float(q), sheet=s2)
    w(sheet=s2)
    # Overlay plot data (what MicroActive puts behind its plots): ads and des side by side, NOT in tabular order
    w("Isotherm Linear Plot", sheet=s2)
    w("Adsorption", None, "Desorption", sheet=s2)
    w("Relative Pressure (P/Po)", "Quantity Adsorbed (cm³/g STP)", "Relative Pressure (P/Po)", "Quantity Adsorbed (cm³/g STP)", sheet=s2)
    for i in range(max(len(pa), len(pd_))):
        cells = [float(pa[i]) if i < len(pa) else None, float(qa[i]) if i < len(pa) else None,
                 float(pd_[i]) if i < len(pd_) else None, float(qd[i]) if i < len(pd_) else None]
        w(*cells, sheet=s2)
    w(sheet=s2)
    w("Isotherm Log Plot", sheet=s2)
    w("Relative Pressure (P/Po)", "Quantity Adsorbed (mmol/g)", sheet=s2)  # some exports give mmol/g here
    for p, q in zip(pa, qa):
        w(float(p), float(q / 22.414), sheet=s2)
    w(sheet=s2)
    w("DFT Pore Size", sheet=s2)
    w("Model: N2 @ 77 K on Carbon Slit Pores by NLDFT", sheet=s2)
    w("Pore Width (nm)", "Incremental Pore Volume (cm³/g)", "Cumulative Pore Volume (cm³/g)", "dV/dw Pore Volume (cm³/g·nm)",
      sheet=s2)
    wd = np.linspace(0.35, 3.0, 60)
    dv = 0.9 * np.exp(-((wd - 0.58) / 0.07) ** 2) + 0.35 * np.exp(-((wd - 0.72) / 0.06) ** 2)
    inc = dv * (wd[1] - wd[0]); cum = np.cumsum(inc)
    for a, b, c, d in zip(wd, inc, cum, dv):
        w(float(a), float(b), float(c), float(d), sheet=s2)
    wb.save(path)
    return {"pa": pa, "qa": qa, "pd": pd_, "qd": qd}


if __name__ == "__main__":
    out = os.path.join(ROOT, "example_data", "Sorption")
    make(os.path.join(out, "SampleA_3Flex_full_report_EXAMPLE.xls"))
    make(os.path.join(out, "SampleA_3Flex_full_report_multisheet_EXAMPLE.xls"), sheets="many")
    print("ok")
