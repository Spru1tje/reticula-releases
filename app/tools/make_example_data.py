# ------------------------------------------------------------------ SEM (TIFF + FEI/XL30-style metadata) and EDX maps
def octahedra_image(h=968, w=1280, n=55, size=(60, 140), seed=0, rough=False):
    r = np.random.default_rng(seed)
    yy, xx = np.mgrid[0:h, 0:w]
    img = np.full((h, w), 40.0)
    for _ in range(n):
        cx, cy = r.uniform(0, w), r.uniform(0, h)
        s = r.uniform(*size); th = r.uniform(0, np.pi)
        xr = (xx - cx) * np.cos(th) + (yy - cy) * np.sin(th)
        yr = -(xx - cx) * np.sin(th) + (yy - cy) * np.cos(th)
        m = (np.abs(xr) + np.abs(yr)) < s
        if not m.any():
            continue
        # facet shading (octahedron projection: 4 facets)
        shade = np.where(xr > 0, 1, 0) + 2 * np.where(yr > 0, 1, 0)
        levels = np.array([150, 185, 120, 205]) + r.normal(0, 8)
        edge = (s - (np.abs(xr) + np.abs(yr))) < 3
        val = levels[shade] + 40 * edge
        img[m] = val[m]
    if rough:
        img += 25 * (r.random((h, w)) > 0.985)
    from scipy.ndimage import gaussian_filter
    img = gaussian_filter(img, 1.2) + r.normal(0, 9, (h, w))
    return np.clip(img, 0, 255).astype(np.uint8)


