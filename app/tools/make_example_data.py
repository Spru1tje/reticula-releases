def pv(x, c, w, eta=0.5):
    g = np.exp(-4 * math.log(2) * ((x - c) / w) ** 2)
    l = 1 / (1 + 4 * ((x - c) / w) ** 2)
    return eta * l + (1 - eta) * g


# ------------------------------------------------------------------ PXRD (STOE WinXPOW .xy export)
def pxrd():
    cif = os.path.join(ROOT, "references", "MOF-801_Zr_COD4121459.cif")
    x = np.arange(2.0, 60.0 + 1e-9, 0.015)
    sim, sticks, _ = simulate_pxrd(cif, (2, 60), fwhm=0.14, step=0.015, substitute={"Zr": "Hf"})
    sim_y = np.interp(x, sim.x, sim.y)
    zro2 = sum(a * pv(x, c, 2.2) for c, a in [(30.3, 1.0), (35.2, 0.25), (50.4, 0.55), (60.0, 0.35)])
    for s in SAMPLES:
        bg = 120 * np.exp(-x / 9) + 25 + 0.25 * x
        if s == "ZrO2":
            y = 900 * zro2 + bg + 60 * np.exp(-((x - 25) / 12) ** 2)
        else:
            cryst = {"Sample A": 1.0, "Sample B": 0.8, "PM": 0.85, "Sample C": 0.7}[s]
            y = 5200 * cryst * sim_y + bg
            if s in ("PM", "Sample C"):
                y += 300 * zro2
        y = rng.poisson(np.clip(y, 1, None)).astype(float)
        with open(d("PXRD", f"{FILE[s]}_STOE.xy"), "w", encoding="utf-8") as f:
            f.write(f"# {BANNER}\n# STOE STADI P Combi, Cu Ka1 (1.540598 A), Debye-Scherrer, IP-PSD; WinXPOW 'Export ASCII .xy'\n")
            for a, b in zip(x, y):
                f.write(f"{a:9.3f} {b:10.1f}\n")


