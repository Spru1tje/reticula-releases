# ------------------------------------------------------------------ TGA
def tga_curve(T, steps, residue):
    """steps: list of (T_mid, width, mass_loss_%)"""
    w = np.full_like(T, 100.0)
    for c, wd, dm in steps:
        w -= dm / (1 + np.exp(-(T - c) / wd))
    return w


def composition_masses(L, form, ss, cl, water, extraZrO2_frac=0.0):
    """Return W200 (dry, hydroxylated) / Wplat (dehydroxylated, caps gone, sulfosuccinate partly) / Wend for an Hf-MOF-801."""
    MHf = AW["Hf"]
    fum, fmt, ssm = molar_mass("C4H2O4"), molar_mass("CHO2"), molar_mass("C4H4O7S")
    w = 12 - 2 * L - form - 2 * ss - cl
    M200 = 6 * MHf + 4 * 15.999 + 4 * 17.007 + L * fum + form * fmt + ss * ssm + cl * 35.45 + w * (17.007 + 18.015)
    Mrt = M200 + water * 18.015
    Mpl = 6 * oxide_mass(1) + L * (fum - 15.999)    # formate, sulfosuccinate (decomposed) and Cl gone
    Mend = 6 * oxide_mass(1)
    return Mrt, M200, Mpl, Mend


