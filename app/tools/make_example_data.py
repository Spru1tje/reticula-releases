# ------------------------------------------------------------------ ICP (Syngistix CSV), XRF, Cl, titration
def icp(meta):
    rows = []
    # digest: 10.0 mg in 50.0 mL -> mg/L = wt% * 2
    for s in SAMPLES:
        if s in ("ZrO2",):
            hf, zr, S = 0.002, 72.0, 0.0
        elif s == "PM":
            hf, zr, S = 44.0, 8.5, 1.3
        else:
            m = meta.get(s)
            L, fm, ss, cl, wat, fz = (m["L"], m["formate"], m["sulfosuccinate"], m["Cl"], m["water"], m["extra_ZrO2_wt_frac"])
            Mrt, *_ = composition_masses(L, fm, ss, cl, wat)
            hf = 100 * 6 * AW["Hf"] / Mrt * (1 - fz)
            zr = 100 * fz * AW["Zr"] / oxide_mass(0) + 0.35 * hf / 100   # ~0.35 % Zr impurity in HfCl4
            S = 100 * ss * AW["S"] / Mrt * (1 - fz)
        for el, line, wt in [("Hf", "277.336", hf), ("Zr", "343.823", zr), ("S", "180.669", S)]:
            c = wt * 10.0 / 50.0 * 10  # mg/L for 10 mg in 50 mL
            reps = c * (1 + rng.normal(0, 0.012, 3))
            rows.append({"Sample ID": s, "Analyte Name": f"{el} {line}", "Int (Corr)": round(reps.mean() * 5200, 1),
                         "Conc (Calib)": round(reps.mean(), 4), "Units": "mg/L", "SD": round(reps.std(ddof=1), 4),
                         "%RSD": round(100 * reps.std(ddof=1) / max(reps.mean(), 1e-9), 2), "Date": "11/12/2026"})
    with open(d("ICP", "ICP-OES_Syngistix_export.csv"), "w", encoding="utf-8") as f:
        f.write(f"{BANNER}\nMethod: Zr_Hf_S_digest.mth,Digest 10.0 mg / 50.0 mL\n")
